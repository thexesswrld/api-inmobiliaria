-- =====================================================================
--  BASE DE DATOS: INMOBILIARIA — ESQUEMA
--  Motor: PostgreSQL 13+
--
--  Este archivo contiene SOLO estructura: tablas, llaves, restricciones,
--  índices y comentarios. Las reglas de negocio (triggers y funciones)
--  están en la carpeta negocio/ y las vistas en vistas/.
--
--  CONVENCIONES
--  ------------
--  * Prefijos por módulo: auth_ (seguridad), gen_ (generales),
--    per_ (personas), pro_ (proyectos), ven_ (comercial/ventas).
--  * Todas las tablas tienen columnas de auditoría:
--      estado                  1 = activo, 0 = eliminado lógico
--      id_usuario_creacion     usuario que creó el registro
--      id_usuario_modificacion último usuario que lo modificó
--      fecha_creacion          se llena sola (now())
--      fecha_modificacion      se actualiza sola con un trigger
--  * Las columnas tipo_x / estado_x apuntan a gen_listas_de_opciones.
--    Cada opción tiene un "codigo" fijo (ej. 'VENDIDO') para que el
--    backend no dependa del id numérico.
--  * Montos: numeric(14,2). Tipo de cambio: numeric(10,4).
-- =====================================================================

BEGIN;

-- Actualiza fecha_modificacion en cada UPDATE (se asigna a todas las tablas al final)
CREATE OR REPLACE FUNCTION fn_set_fecha_modificacion()
RETURNS trigger AS $$
BEGIN
  NEW.fecha_modificacion := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- =====================================================================
-- 1. MÓDULO GENERALES (gen_)
-- =====================================================================

CREATE TABLE gen_listas (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo                   varchar(50)  NOT NULL UNIQUE,
  nombre                   varchar(100) NOT NULL,
  descripcion              varchar(255),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE  gen_listas IS 'Catálogo de listas configurables. Cada lista agrupa opciones en gen_listas_de_opciones.';
COMMENT ON COLUMN gen_listas.codigo IS 'Identificador fijo de la lista usado por el sistema (ej. ESTADO_VENTA). No cambiar una vez en producción.';

CREATE TABLE gen_listas_de_opciones (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lista                 integer NOT NULL REFERENCES gen_listas(id),
  codigo                   varchar(50)  NOT NULL,
  nombre                   varchar(100) NOT NULL,
  codigo_externo           varchar(10),
  orden                    smallint NOT NULL DEFAULT 0,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_opcion_lista_codigo UNIQUE (id_lista, codigo)
);
COMMENT ON TABLE  gen_listas_de_opciones IS 'Valores posibles de cada lista. Las columnas tipo_x / estado_x de otras tablas apuntan aquí.';
COMMENT ON COLUMN gen_listas_de_opciones.codigo IS 'Código fijo usado por el backend (ej. CANCELADA). El nombre visible puede cambiar; el código no.';
COMMENT ON COLUMN gen_listas_de_opciones.codigo_externo IS 'Código en un sistema externo, p. ej. catálogos SUNAT (01 = Factura, 6 = RUC, PEN = Soles).';
COMMENT ON COLUMN gen_listas_de_opciones.orden IS 'Orden de aparición en combos/listas del frontend.';

-- Ubigeo: país > departamento > provincia > distrito
CREATE TABLE gen_pais (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre                   varchar(100) NOT NULL UNIQUE,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE gen_pais IS 'Países.';

CREATE TABLE gen_departamento (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pais                  integer NOT NULL REFERENCES gen_pais(id),
  nombre                   varchar(100) NOT NULL,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_departamento_pais UNIQUE (id, id_pais)  -- soporte para FK compuesta
);
COMMENT ON TABLE gen_departamento IS 'Departamentos (regiones) de un país.';

CREATE TABLE gen_provincia (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_departamento          integer NOT NULL REFERENCES gen_departamento(id),
  nombre                   varchar(100) NOT NULL,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_provincia_departamento UNIQUE (id, id_departamento)
);
COMMENT ON TABLE gen_provincia IS 'Provincias de un departamento.';

CREATE TABLE gen_distrito (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_provincia             integer NOT NULL REFERENCES gen_provincia(id),
  nombre                   varchar(100) NOT NULL,
  ubigeo                   char(6) UNIQUE,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_distrito_provincia UNIQUE (id, id_provincia)
);
COMMENT ON TABLE  gen_distrito IS 'Distritos de una provincia.';
COMMENT ON COLUMN gen_distrito.ubigeo IS 'Código UBIGEO INEI de 6 dígitos. char(6) para no perder el cero inicial (ej. 010101).';

CREATE TABLE gen_empresa (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre                   varchar(200) NOT NULL,
  ruc                      char(11) NOT NULL UNIQUE CHECK (ruc ~ '^[0-9]{11}$'),
  direccion                varchar(255),
  logo                     varchar(500),
  id_pais                  integer REFERENCES gen_pais(id),
  id_departamento          integer,
  id_provincia             integer,
  id_distrito              integer,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  -- FKs compuestas: distrito/provincia/departamento/país coherentes
  CONSTRAINT fk_empresa_departamento FOREIGN KEY (id_departamento, id_pais)      REFERENCES gen_departamento (id, id_pais),
  CONSTRAINT fk_empresa_provincia    FOREIGN KEY (id_provincia, id_departamento) REFERENCES gen_provincia (id, id_departamento),
  CONSTRAINT fk_empresa_distrito     FOREIGN KEY (id_distrito, id_provincia)     REFERENCES gen_distrito (id, id_provincia)
);
COMMENT ON TABLE  gen_empresa IS 'Empresas emisoras (multi-empresa). Cada una tiene su RUC, proyectos, cuentas y series de comprobantes.';
COMMENT ON COLUMN gen_empresa.ruc IS 'RUC de 11 dígitos. char(11): no cabe en un int.';
COMMENT ON COLUMN gen_empresa.logo IS 'Ruta o URL del logo.';

CREATE TABLE gen_cuenta_bancaria (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa               integer NOT NULL REFERENCES gen_empresa(id),
  banco                    varchar(100) NOT NULL,
  tipo_moneda              integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  numero_cuenta            varchar(30)  NOT NULL,
  cci                      char(20) CHECK (cci ~ '^[0-9]{20}$'),
  descripcion              varchar(255),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_cuenta_bancaria UNIQUE (banco, numero_cuenta)
);
COMMENT ON TABLE  gen_cuenta_bancaria IS 'Cuentas de la empresa donde ingresan los pagos (para conciliar con el banco).';
COMMENT ON COLUMN gen_cuenta_bancaria.tipo_moneda IS 'Lista TIPO_MONEDA.';
COMMENT ON COLUMN gen_cuenta_bancaria.cci IS 'Código de cuenta interbancario (20 dígitos).';


-- =====================================================================
-- 2. MÓDULO PERSONAS (per_) — persona base
-- =====================================================================

CREATE TABLE per_persona (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_persona             integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  tipo_documento           integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  documento                varchar(20)  NOT NULL,
  nombre                   varchar(200) NOT NULL,
  apellido_paterno         varchar(100),
  apellido_materno         varchar(100),
  correo                   varchar(150),
  telefono                 varchar(20),
  direccion                varchar(255),
  id_pais                  integer REFERENCES gen_pais(id),
  id_departamento          integer,
  id_provincia             integer,
  id_distrito              integer,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_persona_documento UNIQUE (tipo_documento, documento),
  CONSTRAINT fk_persona_departamento FOREIGN KEY (id_departamento, id_pais)      REFERENCES gen_departamento (id, id_pais),
  CONSTRAINT fk_persona_provincia    FOREIGN KEY (id_provincia, id_departamento) REFERENCES gen_provincia (id, id_departamento),
  CONSTRAINT fk_persona_distrito     FOREIGN KEY (id_distrito, id_provincia)     REFERENCES gen_distrito (id, id_provincia)
);
COMMENT ON TABLE  per_persona IS 'Datos comunes de toda persona natural o jurídica. Trabajadores, clientes y usuarios se enlazan aquí.';
COMMENT ON COLUMN per_persona.tipo_persona IS 'Lista TIPO_PERSONA: NATURAL / JURIDICA.';
COMMENT ON COLUMN per_persona.tipo_documento IS 'Lista TIPO_DOCUMENTO: DNI, RUC, CE, PASAPORTE.';
COMMENT ON COLUMN per_persona.nombre IS 'Persona natural: nombres. Persona jurídica: razón social.';
COMMENT ON COLUMN per_persona.apellido_paterno IS 'Solo persona natural.';
COMMENT ON COLUMN per_persona.direccion IS 'Dirección fiscal/domicilio. Se copia al comprobante al emitirlo.';


-- =====================================================================
-- 3. MÓDULO AUTENTICACIÓN (auth_)
-- =====================================================================

CREATE TABLE auth_usuario (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username                 varchar(50)  NOT NULL UNIQUE,
  password_hash            varchar(255) NOT NULL,
  id_persona               integer NOT NULL UNIQUE REFERENCES per_persona(id),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE  auth_usuario IS 'Usuarios que inician sesión. Un usuario = una persona.';
COMMENT ON COLUMN auth_usuario.password_hash IS 'Hash de la contraseña (bcrypt/argon2). Nunca texto plano.';

CREATE TABLE auth_rol (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo                   varchar(50)  NOT NULL UNIQUE,
  nombre                   varchar(100) NOT NULL,
  descripcion              varchar(255),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE auth_rol IS 'Roles del sistema (ADMIN, VENDEDOR, CAJA...).';

CREATE TABLE auth_usuario_rol (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario               integer NOT NULL REFERENCES auth_usuario(id),
  id_rol                   integer NOT NULL REFERENCES auth_rol(id),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_usuario_rol UNIQUE (id_usuario, id_rol)
);
COMMENT ON TABLE auth_usuario_rol IS 'Asignación N:M de roles a usuarios.';

CREATE TABLE auth_permiso (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo                   varchar(100) NOT NULL UNIQUE,
  nombre                   varchar(100) NOT NULL,
  descripcion              varchar(255),
  modulo                   varchar(50)  NOT NULL,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE  auth_permiso IS 'Acciones protegidas del sistema (ej. ven.venta.crear).';
COMMENT ON COLUMN auth_permiso.modulo IS 'Módulo al que pertenece: auth, gen, per, pro, ven.';

CREATE TABLE auth_rol_permiso (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_rol                   integer NOT NULL REFERENCES auth_rol(id),
  id_permiso               integer NOT NULL REFERENCES auth_permiso(id),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_rol_permiso UNIQUE (id_rol, id_permiso)
);
COMMENT ON TABLE auth_rol_permiso IS 'Asignación N:M de permisos a roles.';

CREATE TABLE auth_sesiones (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario               integer NOT NULL REFERENCES auth_usuario(id),
  token_hash               varchar(255) NOT NULL UNIQUE,
  ip                       varchar(45),
  user_agent               varchar(500),
  fecha_inicio             timestamptz NOT NULL DEFAULT now(),
  fecha_fin                timestamptz,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE  auth_sesiones IS 'Sesiones de login. Se cierra llenando fecha_fin y estado = 0.';
COMMENT ON COLUMN auth_sesiones.token_hash IS 'Hash (SHA-256) del token, no el token. Si la tabla se filtra, los tokens no sirven.';
COMMENT ON COLUMN auth_sesiones.ip IS 'varchar(45) para soportar IPv6.';


