-- =====================================================================
-- 7. AUDITORÍA: FKs a auth_usuario + trigger de fecha_modificacion
--    Van al final porque auth_usuario depende de per_persona y
--    per_persona (como todas) tiene columnas de auditoría.
-- =====================================================================
DO $$
DECLARE
  t text;
BEGIN
  FOR t IN
    SELECT table_name FROM information_schema.columns
    WHERE table_schema = current_schema() AND column_name = 'id_usuario_creacion'
  LOOP
    EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (id_usuario_creacion) REFERENCES auth_usuario(id)',
                   t, 'fk_' || t || '_usr_crea');
    EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (id_usuario_modificacion) REFERENCES auth_usuario(id)',
                   t, 'fk_' || t || '_usr_modi');
  END LOOP;

  FOR t IN
    SELECT table_name FROM information_schema.columns
    WHERE table_schema = current_schema() AND column_name = 'fecha_modificacion'
  LOOP
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_modificacion()',
                   'trg_' || t || '_fmod', t);
  END LOOP;
END;
$$;


