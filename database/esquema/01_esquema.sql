CREATE TABLE per_trabajador (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_persona               integer NOT NULL UNIQUE REFERENCES per_persona(id),
  rol_negocio              integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  fecha_nacimiento         date,
  fecha_ingreso            date,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE  per_trabajador IS 'Persona que trabaja en la empresa (asesor de ventas, cobranzas, etc.).';
COMMENT ON COLUMN per_trabajador.rol_negocio IS 'Lista TIPO_ROL_TRABAJADOR. Rol comercial, distinto del rol de seguridad (auth_rol).';

CREATE TABLE per_cliente (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_persona               integer NOT NULL UNIQUE REFERENCES per_persona(id),
  profesion                varchar(100),
  sueldo                   numeric(14,2) CHECK (sueldo >= 0),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz
);
COMMENT ON TABLE  per_cliente IS 'Persona que compra. El número de contratos se obtiene de la vista v_cliente_resumen (no se guarda).';
COMMENT ON COLUMN per_cliente.sueldo IS 'Ingreso declarado, para evaluar financiamiento.';


-- =====================================================================
-- 5. MÓDULO PROYECTOS (pro_)
-- =====================================================================

CREATE TABLE pro_proyecto (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa               integer NOT NULL REFERENCES gen_empresa(id),
  nombre                   varchar(200) NOT NULL,
  tipo_proyecto            integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  direccion                varchar(255),
  logo                     varchar(500),
  id_pais                  integer REFERENCES gen_pais(id),
  id_departamento          integer,
  id_provincia             integer,
  id_distrito              integer,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT fk_proyecto_departamento FOREIGN KEY (id_departamento, id_pais)      REFERENCES gen_departamento (id, id_pais),
  CONSTRAINT fk_proyecto_provincia    FOREIGN KEY (id_provincia, id_departamento) REFERENCES gen_provincia (id, id_departamento),
  CONSTRAINT fk_proyecto_distrito     FOREIGN KEY (id_distrito, id_provincia)     REFERENCES gen_distrito (id, id_provincia)
);
COMMENT ON TABLE  pro_proyecto IS 'Proyecto inmobiliario (lotización, edificio, condominio...).';
COMMENT ON COLUMN pro_proyecto.tipo_proyecto IS 'Lista TIPO_PROYECTO.';
COMMENT ON COLUMN pro_proyecto.id_distrito IS 'Se guardan los 4 niveles de ubigeo para filtrar sin JOINs; las FKs compuestas impiden combinaciones incoherentes.';

CREATE TABLE pro_sector (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proyecto              integer NOT NULL REFERENCES pro_proyecto(id),
  id_sector_padre          integer,
  nombre                   varchar(100) NOT NULL,
  codigo                   varchar(30),
  orden                    integer NOT NULL DEFAULT 0,
  tipo_sector              integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_sector_codigo    UNIQUE (id_proyecto, codigo),
  CONSTRAINT uq_sector_proyecto  UNIQUE (id, id_proyecto),   -- soporte para FKs compuestas
  CONSTRAINT ck_sector_no_autopadre CHECK (id_sector_padre IS NULL OR id_sector_padre <> id),
  -- El padre debe ser del MISMO proyecto
  CONSTRAINT fk_sector_padre_mismo_proyecto
      FOREIGN KEY (id_sector_padre, id_proyecto) REFERENCES pro_sector (id, id_proyecto)
);
COMMENT ON TABLE  pro_sector IS 'División jerárquica del proyecto: Etapa > Manzana, Torre > Piso, etc.';
COMMENT ON COLUMN pro_sector.id_sector_padre IS 'NULL = sector raíz. Debe pertenecer al mismo proyecto (FK compuesta).';
COMMENT ON COLUMN pro_sector.tipo_sector IS 'Lista TIPO_SECTOR: ETAPA, MANZANA, TORRE, PISO, BLOQUE, ZONA.';

CREATE TABLE pro_unidad (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sector                integer NOT NULL REFERENCES pro_sector(id),
  nombre                   varchar(100) NOT NULL,
  tipo_unidad              integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  precio                   numeric(14,2) CHECK (precio >= 0),
  area_proyectada          numeric(12,2) CHECK (area_proyectada >= 0),
  area_superficie          numeric(12,2) CHECK (area_superficie >= 0),
  estado_comercial         integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  id_propietario           integer REFERENCES per_cliente(id),
  atributos                jsonb NOT NULL DEFAULT '{}'::jsonb,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  CONSTRAINT uq_unidad_nombre UNIQUE (id_sector, nombre)
);
COMMENT ON TABLE  pro_unidad IS 'Bien vendible: lote, departamento, casa, estacionamiento, etc.';
COMMENT ON COLUMN pro_unidad.nombre IS 'Único dentro del sector (no dos "Lote 5" en la misma manzana).';
COMMENT ON COLUMN pro_unidad.precio IS 'Precio de lista vigente. El precio pactado se guarda en ven_detalle_venta.';
COMMENT ON COLUMN pro_unidad.area_proyectada IS 'Área según proyecto (m²).';
COMMENT ON COLUMN pro_unidad.area_superficie IS 'Área real/inscrita (m²).';
COMMENT ON COLUMN pro_unidad.estado_comercial IS 'Lista ESTADO_UNIDAD: DISPONIBLE, SEPARADO, VENDIDO, ENTREGADO, BLOQUEADO.';
COMMENT ON COLUMN pro_unidad.id_propietario IS 'Comprador actual (atajo). Se llena cuando la venta queda CANCELADA o ENTREGADA.';
COMMENT ON COLUMN pro_unidad.atributos IS 'Características variables por tipo: {"dormitorios":3,"banos":2,"vista":"parque"}.';

CREATE TABLE pro_modelo (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proyecto              integer NOT NULL REFERENCES pro_proyecto(id),
  id_sector                integer,
  id_unidad                integer REFERENCES pro_unidad(id),
  tipo_modelo              integer NOT NULL REFERENCES gen_listas_de_opciones(id),
  nombre                   varchar(150) NOT NULL,
  ruta                     varchar(500) NOT NULL,
  version                  integer NOT NULL DEFAULT 1,
  es_principal             boolean NOT NULL DEFAULT false,
  orden                    integer NOT NULL DEFAULT 0,
  estado                   smallint NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  id_usuario_creacion      integer,
  id_usuario_modificacion  integer,
  fecha_creacion           timestamptz NOT NULL DEFAULT now(),
  fecha_modificacion       timestamptz,
  -- Un modelo pertenece al proyecto, a UN sector o a UNA unidad (no a ambos)
  CONSTRAINT ck_modelo_un_duenio CHECK (NOT (id_sector IS NOT NULL AND id_unidad IS NOT NULL)),
  -- El sector debe ser del mismo proyecto del modelo
  CONSTRAINT fk_modelo_sector_mismo_proyecto
      FOREIGN KEY (id_sector, id_proyecto) REFERENCES pro_sector (id, id_proyecto)
);
COMMENT ON TABLE  pro_modelo IS 'Imágenes/planos/renders/3D. DUEÑO: solo id_proyecto = del proyecto; + id_sector = del sector; + id_unidad = de la unidad.';
